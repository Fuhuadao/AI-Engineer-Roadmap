# 运用input()语句输入
print("你的名字是?")
name = input()
print(f"我知道了，你的名字是{name}")
# 简化input（）的输入
name = input("你的名字是：")
print(f"我知道了，你的名字是{name}")

# 定义变量名
user_name = input("您好：")
user_type = input("您是尊贵的：")
print(f"您好{user_name},您是{user_type}用户，欢迎您的光临。") #输出结果

# 比较运算符的使用
num1 = 23
num2 = 34
print(f"num1 == num2的结果：{num1 == num2}")
print(f"num1 != num2的结果：{num1 != num2}")
print(f"num1 < num2的结果：{num1 < num2}")
print(f"num1 > num2的结果：{num1 > num2}")
print(f"num1 <= num2的结果：{num1 <= num2}")
print(f"num1 >= num2的结果：{num1 >= num2}")