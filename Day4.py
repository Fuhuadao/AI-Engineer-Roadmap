# 赋值运算符
num = 9
num += 1
print("num += 1:", num)
num -= 2
print("num -= 2:", num)
num *= 2
print("num *= 2:", num)
num /= 2
print("num /= 2:", num)
num %= 2
print("num %= 2:", num)
num **= 2
print("num **= 2:", num)

